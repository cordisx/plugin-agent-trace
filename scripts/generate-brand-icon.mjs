import { readFile, writeFile } from 'node:fs/promises'

const asset = new URL('../assets/agent-trace.png', import.meta.url)
const target = new URL('../src/brand-icon.ts', import.meta.url)
const data = (await readFile(asset)).toString('base64')
const source = `// Generated by scripts/generate-brand-icon.mjs from assets/agent-trace.png.\n`
  + `import type { CordisXPluginBrandIcon } from 'cordisx/contracts'\n\n`
  + `export const icon = Object.freeze(\n  {\n`
  + `    mediaType: 'image/png',\n`
  + `    data:\n      '${data}',\n`
  + `  } satisfies CordisXPluginBrandIcon,\n)\n`

if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== source) {
    throw new Error('Brand icon is stale; run npm run icon:generate')
  }
} else {
  await writeFile(target, source)
}
